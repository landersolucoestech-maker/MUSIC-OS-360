#!/usr/bin/env node
/**
 * scripts/naming/render-naming-docs.mjs
 *
 * Renders the GENERATED naming documents from the single authority
 * docs/naming/canonical-naming-map.json:
 *   - docs/NAMING_NORMALIZATION_CANONICAL_MAP.md (conventions, glossary,
 *     concept matrix, rename ledger, exception ledger, blockers)
 *   - docs/NAMING_NORMALIZATION_STATUS.md (per-concept status + open conflicts)
 *
 *   node scripts/naming/render-naming-docs.mjs          # write both
 *   node scripts/naming/render-naming-docs.mjs --check  # CI: fail when stale or empty
 *
 * Root cause of the empty status document (found 2026-09-26): the generator was
 * MISSING — the pack declared the file a per-install placeholder, the skills only
 * said "update the status", nothing produced it, and CI never validated it, so it
 * stayed an empty table while the map grew to 48 concepts. The status vocabulary
 * had also drifted from .claude/contracts/canonical-map-entry.schema.json
 * (map-incompatible); entries now carry the schema `status` plus a richer
 * `disposition`.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { ROOT, loadAuthority, validateStructure } from "./canonical-map.mjs";

const MAP_MD = path.join(ROOT, "docs/NAMING_NORMALIZATION_CANONICAL_MAP.md");
const STATUS_MD = path.join(ROOT, "docs/NAMING_NORMALIZATION_STATUS.md");
const CONFLICTS = path.join(ROOT, ".claude/ops/records/conflict");
const GENERATED = "<!-- GENERATED by scripts/naming/render-naming-docs.mjs from docs/naming/canonical-naming-map.json. Do not edit; edit the JSON and re-run. -->";

const cell = (v) => {
  if (v == null || v === "") return "—";
  const s = Array.isArray(v) ? v.join(", ") : String(v);
  return s.replace(/\|/g, "\\|").replace(/\n+/g, " ");
};
const table = (headers, rows) => [
  `| ${headers.join(" | ")} |`,
  `|${headers.map(() => "---").join("|")}|`,
  ...rows.map((r) => `| ${r.map(cell).join(" | ")} |`),
];

function openConflicts() {
  if (!fs.existsSync(CONFLICTS)) return [];
  return fs.readdirSync(CONFLICTS).filter((f) => f.endsWith(".json"))
    .map((f) => JSON.parse(fs.readFileSync(path.join(CONFLICTS, f), "utf8")))
    .filter((c) => (c.status ?? "OPEN") !== "RESOLVED");
}

export function renderMap(map) {
  const c = map.conventions;
  const out = [
    "# Naming Normalization — Canonical Map",
    "",
    GENERATED,
    "",
    "Single authority: `docs/naming/canonical-naming-map.json` (entry schema: `.claude/contracts/canonical-map-entry.schema.json`, plus",
    "`id`/`disposition` and the Cluster Zero matrix fields). Narrative background: `docs/naming/decision-records.md` (non-authoritative).",
    "Guards: `scripts/naming/technical-naming-census.mjs --check` (no new Portuguese technical names), `scripts/naming/validate-canonical-map.mjs`",
    "(map vs live schema), `scripts/naming/render-naming-docs.mjs --check` (generated docs in sync).",
    "",
    "## Naming standard",
    "",
    `- **Language rule.** ${c.languageRule}`,
    `- **Acronyms.** ${c.acronyms}`,
    ...Object.entries(c.pluralization).map(([k, v]) => `- **${k}.** ${v}`),
    "",
    "## Canonical technical glossary",
    "",
    ...table(["Term", "Definition", "Disallowed ambiguous usages", "Related terms", "ID namespace"],
      map.glossary.map((g) => [g.term, g.definition, g.disallowedUsages, g.relatedTerms, g.idNamespace])),
    "",
    "## Concept matrix",
    "",
    ...table(
      ["Concept ID", "Business concept", "Current technical name", "Layer", "Language", "Canonical English name", "Definition", "Producers", "Consumers", "Rename required", "Migration required", "Status"],
      map.concepts.map((x) => [
        x.id, x.concept, x.currentTechnicalName ?? (x.legacyAliases?.length ? x.legacyAliases : x.database), x.layer ?? (x.database ? "database" : "application"),
        x.language ?? (x.disposition === "DONE" ? "English" : "mixed"), x.canonicalEnglishName ?? x.application ?? x.database, x.definition ?? x.notes,
        x.producers, x.consumers, x.renameRequired ?? (x.status === "done" ? "no" : "yes"), x.migrationRequired ?? (x.disposition === "MIGRATION_REQUIRED" ? "yes" : "no"),
        `${x.status} / ${x.disposition}`,
      ]),
    ),
    "",
    "## Layer mapping (pack schema view)",
    "",
    ...table(["Concept ID", "Concept", "Database", "Application", "API", "Event/queue", "Display (pt-BR)", "Legacy aliases", "Status"],
      map.concepts.map((x) => [x.id, x.concept, x.database, x.application, x.api, x.eventOrQueue, x.displayPtBr, x.legacyAliases, x.status])),
    "",
    "## Rename ledger",
    "",
    ...table(["Rename ID", "Old name", "New name", "Type", "Paths", "Producers", "Consumers", "API impact", "DB impact", "Env impact", "Compatibility", "Tests", "Commit"],
      map.renames.map((r) => [r.id, r.oldName, r.newName, r.type, r.paths, r.producers, r.consumers, r.apiImpact, r.dbImpact, r.envImpact, r.compatibility, r.tests, r.commit])),
    "",
    "## Exception ledger",
    "",
    "Every Portuguese technical name that remains has exactly one row here; the census guard uses this table as its only suppression list.",
    "",
    ...table(["Item", "Path", "Current name", "Layer", "Exception class", "Reason", "Consumer", "Owner", "Removal condition", "Target state", "Status"],
      map.exceptions.map((e) => [e.item, e.path, e.currentName, e.layer, e.exceptionClass, e.reason, e.consumer, e.owner, e.removalCondition, e.targetState, e.status])),
    "",
    "## Blockers",
    "",
    ...(map.blockers.length
      ? table(["ID", "Item", "Exact blocker", "Evidence", "Independent work completed", "Required action"], map.blockers.map((b) => [b.id, b.item, b.blocker, b.evidence, b.independentWorkCompleted, b.requiredAction]))
      : ["None."]),
    "",
  ];
  return out.join("\n");
}

export function renderStatus(map) {
  const conflicts = openConflicts();
  const counts = {};
  for (const x of map.concepts) counts[`${x.status}/${x.disposition}`] = (counts[`${x.status}/${x.disposition}`] ?? 0) + 1;
  return [
    "# Naming Normalization — Status",
    "",
    GENERATED,
    "",
    "Per-concept status derived from the canonical naming map plus open `.claude/ops/records/conflict/` records.",
    "",
    ...table(["Concept ID", "Concept", "Status", "Disposition", "Open conflict?"],
      map.concepts.map((x) => [x.id, x.concept, x.status, x.disposition,
        conflicts.some((k) => String(k.concept ?? k.subject ?? "").toLowerCase() === x.concept.toLowerCase()) ? "yes" : "no"])),
    "",
    `Concepts: ${map.concepts.length}. Renames: ${map.renames.length}. Exceptions: ${map.exceptions.length}. Blockers: ${map.blockers.length}.`,
    `By status/disposition: ${Object.entries(counts).sort().map(([k, v]) => `${k} ${v}`).join(", ")}.`,
    "",
  ].join("\n");
}

function main() {
  const map = loadAuthority();
  const problems = validateStructure(map);
  if (problems.length) {
    console.error(`canonical-naming-map.json is invalid:\n  ${problems.join("\n  ")}`);
    process.exit(1);
  }
  const outputs = [[MAP_MD, renderMap(map)], [STATUS_MD, renderStatus(map)]];
  if (process.argv[2] === "--check") {
    let bad = false;
    for (const [file, text] of outputs) {
      const cur = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
      const rows = cur.split("\n").filter((l) => /^\| (NC|CZ)-\d+/.test(l)).length;
      if (map.concepts.length > 0 && rows === 0) { console.error(`${path.relative(ROOT, file)} has no concept rows while the map has ${map.concepts.length}`); bad = true; }
      else if (cur !== text) { console.error(`${path.relative(ROOT, file)} is stale; run node scripts/naming/render-naming-docs.mjs`); bad = true; }
    }
    if (bad) process.exit(1);
    console.log(`naming docs in sync (${map.concepts.length} concepts, ${map.renames.length} renames, ${map.exceptions.length} exceptions)`);
    return;
  }
  for (const [file, text] of outputs) fs.writeFileSync(file, text);
  console.log(`rendered naming docs (${map.concepts.length} concepts, ${map.renames.length} renames, ${map.exceptions.length} exceptions)`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
