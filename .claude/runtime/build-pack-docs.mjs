#!/usr/bin/env node
// Generates the map documents of the MUSIC OS 360 pack under .claude/docs/pack/ from the machine
// registries (pack-registry.json, routing.json, workflows, ownership, policies, gates, contracts), so the
// documentation cannot describe a capability that does not exist and cannot drift without a failing check.
//
//   node .claude/runtime/build-pack-docs.mjs            write the generated documents
//   node .claude/runtime/build-pack-docs.mjs --check    exit 1 when a generated document is stale
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { buildRegistry } from "./build-pack-registry.mjs";
import { validatePack } from "./validate-pack-contracts.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT_DEFAULT = join(__dirname, "..", "..");
const OUT_DIR = ".claude/docs/pack";
const readJson = (p) => JSON.parse(readFileSync(p, "utf8"));
const esc = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");
const list = (a) => (a && a.length ? a.map((x) => `\`${x}\``).join(", ") : "none");
const GENERATED = "<!-- Generated by .claude/runtime/build-pack-docs.mjs from the pack registries. Do not edit by hand. -->";

function groupBy(items, key) {
  const m = new Map();
  for (const it of items) m.set(it[key], [...(m.get(it[key]) || []), it]);
  return [...m.entries()].sort((a, b) => String(a[0]).localeCompare(String(b[0])));
}

export function buildDocs(root = ROOT_DEFAULT) {
  const registry = buildRegistry(root);
  const routing = readJson(join(root, ".claude", "registry", "routing.json"));
  const ownership = readJson(join(root, ".claude", "ownership.json"));
  const authority = readJson(join(root, ".claude", "policies", "authority.json"));
  const dir = (rel, ext) => (existsSync(join(root, rel)) ? readdirSync(join(root, rel)).filter((f) => f.endsWith(ext)).sort() : []);
  const docs = {};

  // agents
  let md = `# Agent map\n\n${GENERATED}\n\n${registry.agents.length} pack agents, grouped by domain. Writers hold \`Edit\`/\`Write\` and a declared write scope; every other agent is read-only.\n`;
  for (const [domain, agents] of groupBy(registry.agents, "domain")) {
    md += `\n## ${domain} (${agents.length})\n\n| Agent | Kind | Tools | Writes | Capabilities | Approval |\n|---|---|---|---|---|---|\n`;
    for (const a of agents) md += `| \`${a.name}\` | ${a.kind} | ${a.tools.join(", ")} | ${a.writes.length ? a.writes.map((w) => `\`${w}\``).join("<br>") : "none"} | ${list(a.capabilities)} | ${a.approval} |\n`;
  }
  docs["agents-map.md"] = md;

  // skills
  md = `# Skill map\n\n${GENERATED}\n\n${registry.skills.length} pack skills. \`mutates\` marks skills that change state through their guarded path; \`approval\` is the action class a human must approve first.\n`;
  for (const [domain, skills] of groupBy(registry.skills, "domain")) {
    md += `\n## ${domain} (${skills.length})\n\n| Skill | Kind | Mutates | Approval | Consumers |\n|---|---|---|---|---|\n`;
    for (const s of skills) md += `| \`${s.name}\` | ${s.kind} | ${s.mutates ? "yes" : "no"} | ${s.approval} | ${list(s.consumers)} |\n`;
  }
  docs["skills-map.md"] = md;

  // capabilities
  md = `# Capability map\n\n${GENERATED}\n\n${registry.capabilities.length} capabilities. A capability without an executor agent or without a skill is a validation error.\n`;
  for (const [domain, caps] of groupBy(registry.capabilities, "domain")) {
    md += `\n## ${domain} (${caps.length})\n\n| Capability | Executors | Skills | Validation | Evidence | Approval |\n|---|---|---|---|---|---|\n`;
    for (const c of caps) md += `| \`${c.id}\` | ${list(c.executors)} | ${list(c.skills)} | ${esc(c.validation.join("; "))} | ${esc(c.evidence.join("; "))} | ${c.approval} |\n`;
  }
  docs["capabilities-map.md"] = md;

  // routing
  md = `# Routing map\n\n${GENERATED}\n\nRouting is \`task -> intent -> capabilities -> agent -> skills -> tools -> validation -> evidence\`. Executed by \`.claude/runtime/route-task.mjs\` over \`.claude/registry/routing.json\`.\n\n## Intents (${routing.intents.length})\n\n| Intent | Domain | Keywords | Capabilities |\n|---|---|---|---|\n`;
  for (const i of [...routing.intents].sort((a, b) => a.intent.localeCompare(b.intent))) md += `| \`${i.intent}\` | ${i.domain} | ${esc(i.keywords.join(", "))} | ${list(i.capabilities)} |\n`;
  md += `\n## High-impact signals\n\n| Class | Patterns |\n|---|---|\n`;
  for (const s of routing.highImpactSignals || []) md += `| \`${s.class}\` | ${esc((s.patterns || []).join(", "))} |\n`;
  docs["routing-map.md"] = md;

  // workflows
  md = `# Workflow map\n\n${GENERATED}\n\n${dir(".claude/workflows", ".json").length} workflows under \`.claude/workflows\`. A phase marked **approval** waits for a recorded human decision; a high-impact skill must sit in or directly after such a phase.\n`;
  for (const f of dir(".claude/workflows", ".json")) {
    const w = readJson(join(root, ".claude", "workflows", f));
    md += `\n## ${w.name}\n\n${w.description || ""}\n\n| Phase | Agents | Skills | Gates | Depends on |\n|---|---|---|---|---|\n`;
    for (const p of w.phases) md += `| \`${p.id}\`${p.approvalRequired ? " **approval**" : ""} | ${list(p.requiredAgents)} | ${list(p.requiredSkills)} | ${list(p.gates)} | ${list(p.dependsOn)} |\n`;
    md += `\nRecovery: ${w.recoveryPath || "none"}\n\nCompletion: ${(w.completionConditions || []).map(esc).join("; ") || "none"}\n`;
  }
  docs["workflows-map.md"] = md;

  // ownership
  md = `# Ownership map\n\n${GENERATED}\n\n${ownership.owners.length} owner entries. Conflict rule: ${esc(ownership.conflictRule)}\n\n| Agent | Writes |\n|---|---|\n`;
  for (const o of [...ownership.owners].sort((a, b) => a.agent.localeCompare(b.agent))) md += `| \`${o.agent}\` | ${o.writes.length ? o.writes.map((w) => `\`${w}\``).join("<br>") : "none"} |\n`;
  docs["ownership-map.md"] = md;

  // contracts, policies, gates inventory
  md = `# Contracts, policies and gates\n\n${GENERATED}\n\n## Contracts (${dir(".claude/contracts", ".schema.json").length})\n\n| Contract | Description |\n|---|---|\n`;
  for (const f of dir(".claude/contracts", ".schema.json")) md += `| \`${f}\` | ${esc(readJson(join(root, ".claude", "contracts", f)).description || "").slice(0, 220)} |\n`;
  md += `\n## Policies (${dir(".claude/policies", ".json").length})\n\n| Policy | Description |\n|---|---|\n`;
  for (const f of dir(".claude/policies", ".json")) md += `| \`${f}\` | ${esc(readJson(join(root, ".claude", "policies", f)).description || "").slice(0, 220)} |\n`;
  md += `\n## Gates (${dir(".claude/gates", ".json").length})\n\n| Gate | Checks | Description |\n|---|---|---|\n`;
  for (const f of dir(".claude/gates", ".json")) { const g = readJson(join(root, ".claude", "gates", f)); md += `| \`${f}\` | ${list((g.checks || []).map((c) => c.id))} | ${esc(g.description || "").slice(0, 200)} |\n`; }
  md += `\n## Approval action classes (${authority.actionClasses.length})\n\n| Class | Requires approval |\n|---|---|\n`;
  for (const c of authority.actionClasses) md += `| \`${c.name}\` | ${c.requiresApproval ? "yes" : "no"} |\n`;
  docs["contracts-policies-gates.md"] = md;
  // completeness matrix: one row per manifest item (the authoritative agent and skill lists of the mission)
  const manifest = readJson(join(root, ".claude", "registry", "pack-manifest.json"));
  const problems = validatePack(root).problems;
  const inRegistry = new Set([...registry.agents.map((a) => `agent:${a.name}`), ...registry.skills.map((x) => `skill:${x.name}`)]);
  const unavailable = new Map();
  for (const it of manifest.items) {
    if (it.type !== "skill" || !existsSync(join(root, it.file))) continue;
    const t = readFileSync(join(root, it.file), "utf8");
    const m = t.match(/## Capability unavailable\n- required integration: (.*)/);
    if (m) unavailable.set(it.name, m[1].split(",")[0]);
  }
  const states = new Map();
  for (const it of manifest.items) states.set(it.finalState, (states.get(it.finalState) || 0) + 1);
  md = `# Completeness matrix\n\n${GENERATED}\n\n${manifest.items.length} items (${manifest.items.filter((i) => i.type === "agent").length} agents, ${manifest.items.filter((i) => i.type === "skill").length} skills). Final states: ${[...states.entries()].map(([k, v]) => `${k} ${v}`).join(", ")}. Allowed final states are EXISTING_VALID, ENHANCED, CREATED and BLOCKED_EXTERNAL; BLOCKED_EXTERNAL means the item is defined and valid but its execution depends on an external provider that is not configured. Validation column: the result of \`validate-pack-contracts.mjs\` for the item; Evidence column: the command that produces it.\n\n| Item | Type | Batch | Initial | Final | File | Registry | Contract | Validation | Evidence |\n|---|---|---|---|---|---|---|---|---|---|\n`;
  for (const it of manifest.items) {
    const bad = problems.filter((x) => x.includes(` ${it.name}:`)).length;
    const note = unavailable.has(it.name) ? `capability unavailable (${esc(unavailable.get(it.name))})` : "";
    md += `| \`${it.name}\` | ${it.type} | ${it.batch} | ${it.initialState} | ${it.finalState} | \`${it.file}\` | ${inRegistry.has(`${it.type}:${it.name}`) ? "yes" : "no"} | ${existsSync(join(root, it.file)) ? "present" : "missing"} | ${bad ? "FAIL" : "PASS"}${note ? "; " + note : ""} | \`node .claude/runtime/validate-pack-contracts.mjs\` |\n`;
  }
  docs["completeness-matrix.md"] = md;
  return docs;
}

function main() {
  const check = process.argv.includes("--check");
  const root = ROOT_DEFAULT;
  const docs = buildDocs(root);
  const outDir = join(root, OUT_DIR);
  const stale = [];
  if (!check) mkdirSync(outDir, { recursive: true });
  for (const [name, body] of Object.entries(docs)) {
    const p = join(outDir, name);
    const text = body.endsWith("\n") ? body : body + "\n";
    if (check) { if (!existsSync(p) || readFileSync(p, "utf8") !== text) stale.push(name); }
    else writeFileSync(p, text);
  }
  console.log(JSON.stringify({ status: check ? (stale.length ? "STALE" : "PASS") : "WRITTEN", documents: Object.keys(docs).length, stale }));
  if (check && stale.length) process.exitCode = 1;
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
